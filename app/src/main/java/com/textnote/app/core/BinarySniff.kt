package com.textnote.app.core

/**
 * 「这看起来不是文本文件」的判据。
 *
 * ## 判据为什么落在**解码后**的文本上，而不是原始字节
 *
 * 最直觉的做法是「前 N 字节里出现 `0x00` 就是二进制」——git 就是这么判的
 * （`buffer_is_binary`：前 8000 字节里有 NUL 即视为二进制）。但那是给 8 位编码设计的，
 * 直接搬到本项目会**误杀 UTF-16**：UTF-16LE 的 ASCII 文本每隔一个字节就是 `0x00`
 * （`a` 存成 `61 00`），一份完全正常的 UTF-16 文档会被判成二进制。
 *
 * 而本项目已经能正确读 UTF-16（[TextEncoding] 按 BOM 探测），所以这条判据必须**排在 BOM
 * 探测之后**。与其在字节层重新实现一遍编码识别，不如直接用解码结果：解码已经把字节映射成
 * 字符了，UTF-16 的 `61 00` 会变成干净的 `a`，而 JPEG 的头 `FF D8 FF E0 00 10` 解码回来
 * 一定带 NUL 或一堆控制字符。**两种编码路径的差异在这里被自动抹平**。
 *
 * ## 两条规则
 *
 * 1. 采样范围内出现 **NUL（U+0000）** → 二进制。文本文件里出现 NUL 只有两种可能：
 *    文件是二进制，或文件已损坏。保留它是「不许拒绝任何可能的文本」的过度宽容，
 *    代价是用户对着一屏乱码琢磨是不是应用坏了。
 * 2. NUL 之外的控制字符 + 替换字符（U+FFFD）占比超过 [CONTROL_RATIO] → 二进制。
 *    这条是兜底：有些二进制格式（部分压缩流、加密数据）恰好一段里没有 NUL。
 *    阈值取得很高，是因为**误判成二进制比漏判更糟**——前者让用户彻底打不开一份文本，
 *    后者只是维持现状（现在本来就是显示乱码，没有变差）。
 *
 * ## 为什么只看前 [SNIFF_CHARS] 个字符
 *
 * 与 git 的 8000 字节同源，也是为了**代价与文件体积无关**：打开 4MB 文件时不能为了判
 * 「是不是文本」再多扫一遍全篇。代价是「NUL 出现在第 8000 个字符之后」这种情况漏判——
 * 但那种文件在开头 8000 个字符里看起来完全就是文本，用户可以正常读它。
 */
object BinarySniff {

    /** 只看正文最前面这么多个字符。超出的部分不参与判定（见文件注释） */
    const val SNIFF_CHARS = 8_000

    /**
     * 控制字符占比超过这个值就判为二进制。
     *
     * 20% 是刻意取高的：真实文本里出现的控制字符只有制表符与换行（它们不算在内），
     * 偶尔夹杂几个 `\u0001` 之类的旧格式标记不影响判定。而真正的二进制数据里，
     * 控制字符占比通常在 50% 以上。
     */
    const val CONTROL_RATIO = 0.20

    /**
     * 这段文本看起来是不是二进制内容。
     *
     * [text] 必须是**已经解码过**的正文（见文件注释），调用方在
     * `TextEncoding.decode(bytes).text` 上调用它。
     */
    fun looksBinary(text: String): Boolean {
        val limit = minOf(text.length, SNIFF_CHARS)
        if (limit == 0) return false
        var suspicious = 0
        for (i in 0 until limit) {
            val c = text[i]
            // 规则 1：NUL 一票否决，不必再看统计
            if (c == '\u0000') return true
            if (isSuspicious(c)) suspicious++
        }
        return suspicious > limit * CONTROL_RATIO
    }

    /**
     * 算不算「不该出现在文本里」的字符。
     *
     * 制表符、换行、回车、换页**不算**：制表符和换行是最常见的文本控制字符，一份缩进规范的
     * 源码里制表符可能占 5%~10%，算进去会让阈值失去意义；`\f`（换页）是老式纯文本用来分页的，
     * 正常内容里也会出现，算进去会误拒那种文件——而误拒正是这里最不能犯的错。
     *
     * U+FFFD（替换字符）算：它是解码失败的证据。一整篇替换字符通常意味着「这不是这个
     * 编码的文本」，而不是「文件里有特殊字符」。
     */
    private fun isSuspicious(c: Char): Boolean = when {
        c == '\t' || c == '\n' || c == '\r' || c == '\u000C' -> false
        c < ' ' -> true // 其余 C0 控制字符
        c == '\u007F' -> true // DEL
        c == '\uFFFD' -> true // 解码失败的替换字符
        else -> false
    }
}
