package com.textnote.app.core

/**
 * 编辑器能承受多大的文本。**这几个数字是实测出来的，改之前先看项目记忆里的性能表。**
 *
 * 背景：Compose 的 `BasicTextField` 每次文本改动都会重排全文，代价随字符数增长，
 * 而且不是线性的——到某个量级会从「慢」直接变成「卡死」。实测（emulator-5554）：
 * 60K 字符一次输入 101ms、188K 1.1s、900K 输入一个字符 40 秒仍未恢复（界面完全没反应）。
 *
 * 分三档，**每档给用户完全不同的交代**：
 * - 过了 [HIGHLIGHT_CHARS]：只是**不再着色**，文件照常编辑，状态栏语法名后面带 `*`；
 * - 过了 [OPEN_CHARS]：**只读浏览**。可编辑内核在这个体积下没法用，但按行懒加载的
 *   只读渲染器代价与体积无关（实测 188K 与 8MB 都是 30ms 上下），所以「看得见」是做得到的；
 * - 过了 [READ_BYTES]：**不开**。这不再是体验问题而是**内存安全问题**——读进内存会崩。
 */
object EditorLimits {

    /** 超过这个字符数就不做语法着色（着色会把每次编辑的开销再乘 2~4 倍） */
    const val HIGHLIGHT_CHARS = 64_000

    /**
     * 超过这个字符数就在界面上提示「输入可能卡顿」。
     *
     * 与 [HIGHLIGHT_CHARS] 数值相同、含义不同：那个是「不再着色」，这个是「整体偏慢」。
     * 现在恰好同值，是因为两者都由同一份实测数据推出来；将来各自演化，所以分成两个常量，
     * 免得改一个时不小心把另一个也改了。
     */
    const val SLOW_CHARS = 64_000

    /**
     * 超过这个字符数就**不能再编辑**，改成只读浏览。
     *
     * 取 20 万而不是「刚卡的那个点」，是为了留出余量：188K 实测 1.1s/次输入，很难受但还能用；
     * 再往上就滑向卡死。真正的阈值不该靠猜，所以在能测出更细的拐点之前，宁可保守一点。
     */
    const val OPEN_CHARS = 200_000

    /**
     * 读取时最多读这么多字节。**这是唯一一条「读不动就不开」的红线。**
     *
     * 目的不是用户体验，是**防止 OOM**：不加限制的话，用户点一个几百 MB 的文件会直接
     * 把整个文件读进内存然后崩掉。
     *
     * 为什么敢开到 4MB：只读渲染器的代价与体积**无关**，实测到 8MB 仍然平坦
     * （2/4/8MB 的中位帧耗时分别是 29/34/36ms，打开都是 3.1~3.2s）。
     * 所以红线由内存定，而 4MB 连同解码后的 String 大约占十几 MB，安全。
     */
    const val READ_BYTES = 4 * 1024 * 1024

    /** UTF-8 下单个字符最多占的字节数 */
    const val MAX_BYTES_PER_CHAR = 4
}
